use crate::projects::{err, Result};
use serde_json::Value;
use std::{fs,path::Path};

pub fn prepare(staged:&Path, d:&Value)->Result<()> {
    let name=d["name"].as_str().filter(|s| regex::Regex::new(r"^[A-Za-z_]\w{0,62}$").unwrap().is_match(s)).ok_or("Некоректне ім’я змінної Code.")?;
    let cpp=d["cppType"].as_str().filter(|s| ["byte","int","unsigned int","unsigned","long","unsigned long","short","unsigned short","float","double","int8_t","uint8_t","int16_t","uint16_t","int32_t","uint32_t"].contains(s)).ok_or("Непідтримуваний тип змінної Code.")?;
    let min=d["min"].as_i64().filter(|v|v.abs()<=100000).ok_or("Некоректний мінімум.")?;
    let max=d["max"].as_i64().filter(|v|v.abs()<=100000).ok_or("Некоректний максимум.")?;
    if max<=min||max-min>256{return Err("Непідтримуваний діапазон повзунка.".into());}
    let patches=d["patches"].as_array().filter(|p|p.len()==(max-min+1)as usize).ok_or("Відсутні динамічні кадри.")?;
    let mut header=String::from("// Generated by Pinway Code bindings.\n#pragma once\n#include <stdint.h>\nnamespace PinwayDynamic {\nstruct Patch {uint32_t index;uint16_t count,color;};\nstruct Frame {uint32_t first;uint16_t count;};\nconstexpr Patch patches[]={\n");
    let mut offsets=Vec::new();let mut total=0;
    for frame in patches {
        let frame=frame.as_array().filter(|p|p.len()<65535).ok_or("Некоректний динамічний кадр.")?;
        offsets.push((total,frame.len()));
        for patch in frame {
            let p=patch.as_array().filter(|p|p.len()==3).ok_or("Некоректний піксельний фрагмент.")?;
            let i=p[0].as_u64().ok_or("Некоректний індекс.")?;
            let n=p[1].as_u64().filter(|n|*n>0&&*n<=65535).ok_or("Некоректна довжина.")?;
            let color=p[2].as_u64().filter(|n|*n<=65535).ok_or("Некоректний RGB565.")?;
            if i+n>67200{return Err("Фрагмент виходить за межі екрана.".into());}
            header.push_str(&format!("{{{i},{n},{color}}},\n"));total+=1;
            if total>85000{return Err("Забагато графіки для ESP32.".into());}
        }
    }
    if total==0{header.push_str("{0,1,0},\n");}
    header.push_str("};\nconstexpr Frame frames[]={\n");
    for(first,count)in offsets{header.push_str(&format!("{{{first},{count}}},\n"));}
    header.push_str("};\nstruct Slider {int x,y,w,h;};\nconstexpr Slider sliders[]={\n");
    let sliders=d["sliders"].as_array().filter(|s|!s.is_empty()&&s.len()<=20).ok_or("Відсутній повзунок.")?;
    for s in sliders {
        let mut g=Vec::new();for key in ["x","y","width","height"]{g.push(s[key].as_i64().filter(|v|*v>=0&&*v<=280).ok_or("Некоректна область повзунка.")?);}
        if g[2]<1||g[3]<1||g[0]+g[2]>240||g[1]+g[3]>280{return Err("Повзунок виходить за межі екрана.".into());}
        header.push_str(&format!("{{{},{},{},{}}},\n",g[0],g[1],g[2],g[3]));
    }
    header.push_str("};\n}\n");
    let primary=staged.join(format!("{}.ino",staged.file_name().unwrap().to_string_lossy()));
    let mut code=fs::read_to_string(&primary).map_err(err)?;
    if code!=d["code"].as_str().ok_or("Відсутній вихідний скетч.")?{return Err("Code змінився під час підготовки. Повтори збірку.".into());}
    for fun in ["setup","loop"] {
        let re=regex::Regex::new(&format!(r"\bvoid\s+{fun}\s*\(\s*(?:void\s*)?\)\s*\{{")).map_err(err)?;
        if re.find_iter(&code).count()!=1{return Err(format!("Потрібна однозначна функція void {fun}() у скетчі для прив’язки Display."));}
        code=re.replace(&code,format!("void pinwayUser_{fun}() {{")).into_owned();
    }
    if !fs::read_to_string(staged.join("display_ui.cpp")).map_err(err)?.contains("void displayPixels(") ||
       !fs::read_to_string(staged.join("touch.cpp")).map_err(err)?.contains("bool touchPosition(") {
        return Err("Онови адаптери display_ui.cpp і touch.cpp для динамічного Display.".into());
    }
    let runtime=include_str!("display_dynamic.cpp.in").replace("@TYPE@",cpp).replace("@NAME@",name).replace("@MIN@",&min.to_string()).replace("@MAX@",&max.to_string());
    fs::write(staged.join("pinway_dynamic.h"),header).map_err(err)?;
    fs::write(staged.join("pinway_runtime.cpp"),runtime).map_err(err)?;
    fs::write(primary,code).map_err(err)?;
    Ok(())
}


#[cfg(test)]
mod tests {
 use super::*;
 use serde_json::json;
 #[test]
 fn generates_direct_binding_hooks_and_rejects_code_changes_or_out_of_bounds_patches() {
  let temp=tempfile::tempdir().unwrap();let dir=temp.path().join("Example");fs::create_dir(&dir).unwrap();
  let code="int brightness=20;\nvoid setup() {}\nvoid loop(){brightness++;}\n";
  fs::write(dir.join("Example.ino"),code).unwrap();
  fs::write(dir.join("display_ui.cpp"),"void displayPixels(").unwrap();
  fs::write(dir.join("touch.cpp"),"bool touchPosition(").unwrap();
  let input=json!({"name":"brightness","cppType":"int","min":0,"max":1,"initial":0,"patches":[[],[[0,1,65535]]],"sliders":[{"x":20,"y":100,"width":200,"height":48}],"code":code});
  prepare(&dir,&input).unwrap();
  let runtime=fs::read_to_string(dir.join("pinway_runtime.cpp")).unwrap();
  assert!(runtime.contains("extern int brightness;"));assert!(runtime.contains("brightness=(int)"));
  assert!(!runtime.contains("@NAME@"));
  let hooked=fs::read_to_string(dir.join("Example.ino")).unwrap();assert!(hooked.contains("void pinwayUser_setup()"));assert!(hooked.contains("brightness++;"));
  assert!(prepare(&dir,&input).is_err());
  fs::write(dir.join("Example.ino"),code).unwrap();
  let mut bad=input.clone();bad["patches"][1]=json!([[67199,2,0]]);assert!(prepare(&dir,&bad).is_err());
 }
}
