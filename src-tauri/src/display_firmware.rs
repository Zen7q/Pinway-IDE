use crate::{display, projects::{err, Result}};
use serde_json::Value;
use std::{fs, path::Path};

// Generation is confined to the temporary build copy. User C++ is never replaced.
pub fn prepare(root: &Path, staged: &Path, input: &Value, board: &str) -> Result<()> {
    let mut doc = display::load(root)?;
    let target = doc["hardwarePreview"]["target"].as_str();
    if target != Some("TouchLed169/RGB565") {
        if !input.is_null() { return Err("Непідтримуваний адаптер Display.".into()); }
        return Ok(());
    }
    if input.is_null() { return Err("Не підготовлено поточний макет Display. Оновіть Pinway й повторіть завантаження.".into()); }
    if board != "esp32:esp32:esp32" { return Err("Для цього дисплея виберіть ESP32 Dev Module.".into()); }
    doc.as_object_mut().ok_or("Некоректний Display")?.remove("hardwarePreview");
    if input["source"] != doc { return Err("Макет на диску змінився. Повторіть завантаження.".into()); }
    let c = &doc["canvas"];
    if c["width"] != 240 || c["height"] != 280 || c["class"] != "color" {
        return Err("Цей адаптер Display потребує полотно 240 × 280.".into());
    }
    let header = frames_header(&input["runs"])?;
    if !input["dynamic"].is_null() {
        fs::write(staged.join("display_frames.h"), header).map_err(err)?;
        return crate::display_dynamic::prepare(staged, &input["dynamic"]);
    }
    let button = &input["button"];
    let mut geometry = Vec::new();
    for key in ["x", "y", "width", "height"] {
        geometry.push(button[key].as_i64().filter(|v| *v >= 0 && *v <= 280).ok_or("Некоректна область дотику.")?);
    }
    if geometry[2] == 0 || geometry[3] == 0 || geometry[0]+geometry[2]>240 || geometry[1]+geometry[3]>280 {
        return Err("Кнопка виходить за межі дисплея.".into());
    }
    let adapter = fs::read_to_string(staged.join("display_ui.cpp")).map_err(err)?;
    if !adapter.contains("drawFrame(DisplayFrames::on)") || !adapter.contains("drawFrame(DisplayFrames::off)") {
        return Err("Адаптер display_ui.cpp змінено: автоматична підготовка графіки недоступна.".into());
    }
    let hardware = staged.join("hardware.h");
    let mut text = fs::read_to_string(&hardware).map_err(err)?;
    for (name, value) in ["BUTTON_X", "BUTTON_Y", "BUTTON_W", "BUTTON_H"].iter().zip(geometry) {
        let re = regex::Regex::new(&format!(r"(?m)^constexpr int {name} = \d+;$")).map_err(err)?;
        if re.find_iter(&text).count() != 1 { return Err(format!("Не вдалося оновити {name} у копії hardware.h.")); }
        text = re.replace(&text, format!("constexpr int {name} = {value};")).into_owned();
    }
    fs::write(staged.join("display_frames.h"), header).map_err(err)?;
    fs::write(hardware, text).map_err(err)?;
    Ok(())
}

pub(crate) fn frames_header(runs: &Value) -> Result<String> {
    let mut result = String::from("// Generated by Pinway Display for this build.\n#pragma once\n#include <stdint.h>\nnamespace DisplayFrames {\nstruct Run { uint16_t count, color; };\n");
    for name in ["off", "on"] {
        let frame = runs[name].as_array().filter(|v| v.len() <= 67200).ok_or("Відсутні кадри Display.")?;
        result.push_str(&format!("constexpr Run {name}[] = {{\n"));
        let mut pixels = 0u64;
        for run in frame {
            let run = run.as_array().filter(|r| r.len()==2).ok_or("Некоректний кадр Display.")?;
            let count = run[0].as_u64().filter(|n| *n > 0 && *n <= 65535).ok_or("Некоректний RGB565 run.")?;
            let color = run[1].as_u64().filter(|n| *n <= 65535).ok_or("Некоректний RGB565 color.")?;
            pixels += count;
            if pixels > 67200 { return Err("Завеликий кадр Display.".into()); }
            result.push_str(&format!("{{{count},{color}}},\n"));
        }
        if pixels != 67200 { return Err("Неповний кадр Display.".into()); }
        result.push_str("};\n");
    }
    result.push_str("}\n");
    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn updates_moved_touch_target_only_in_build_copy_and_rejects_stale_layout() {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path().canonicalize().unwrap();
        let project = crate::projects::create(&root, "Example", "void setup() {}\nvoid loop() {}\n").unwrap();
        fs::write(project.root.join("display_ui.cpp"), "drawFrame(DisplayFrames::on); drawFrame(DisplayFrames::off);").unwrap();
        let hardware = "constexpr int BUTTON_X = 28;\nconstexpr int BUTTON_Y = 168;\nconstexpr int BUTTON_W = 184;\nconstexpr int BUTTON_H = 68;\n";
        fs::write(project.root.join("hardware.h"), hardware).unwrap();
        fs::write(project.root.join("display_frames.h"), "manual original").unwrap();
        let source = json!({"format":"pinway.display/1","canvas":{"width":240,"height":280,"class":"color"},"pages":[{"id":"led"}]});
        let mut doc = source.clone();doc["hardwarePreview"] = json!({"target":"TouchLed169/RGB565"});
        display::save(&project.root, &doc, &Value::Null).unwrap();
        let work = root.join("build");fs::create_dir(&work).unwrap();
        let staged = crate::projects::stage_generated(&project, &work).unwrap();
        assert_ne!(staged.directory, project.root);
        let runs=json!({"off":[[65535,0],[1665,0]],"on":[[65535,1],[1665,1]]});
        let input=json!({"source":source,"button":{"x":31,"y":156,"width":184,"height":68},"runs":runs});
        prepare(&project.root,&staged.directory,&input,"esp32:esp32:esp32").unwrap();
        assert!(fs::read_to_string(staged.directory.join("hardware.h")).unwrap().contains("BUTTON_X = 31;"));
        assert!(fs::read_to_string(staged.directory.join("hardware.h")).unwrap().contains("BUTTON_Y = 156;"));
        assert_eq!(fs::read_to_string(project.root.join("hardware.h")).unwrap(),hardware);
        assert_eq!(fs::read_to_string(project.root.join("display_frames.h")).unwrap(),"manual original");
        assert!(prepare(&project.root,&staged.directory,&Value::Null,"esp32:esp32:esp32").is_err());
        let mut stale=input.clone();stale["source"]["canvas"]["width"]=json!(200);
        assert!(prepare(&project.root,&staged.directory,&stale,"esp32:esp32:esp32").is_err());
    }
    #[test]
    fn rejects_partial_oversized_and_injected_frames() {
        assert!(frames_header(&json!({"off":[[65535,0],[1665,65535]],"on":[[65535,5],[1665,5]]})).is_ok());
        for value in [json!([[1,0]]),json!([[65535,0],[2000,0]]),json!([[67200,0]]),json!([[65535,"};evil"]]),json!([[0,0]])] {
            assert!(frames_header(&json!({"off":value,"on":value})).is_err());
        }
    }
}
