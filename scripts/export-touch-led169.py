#!/usr/bin/env python3
"""Export the supported TouchLed169 layout to identical RGB565 preview/firmware.
Requires Pillow 12.0.0 and macOS Arial.ttf. Does not upload or edit user handlers.
"""
import base64
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / 'examples/TouchLed169'
LAYOUT = PROJECT / '.pinway/display.json'
FONT = Path('/System/Library/Fonts/Supplemental/Arial.ttf')


def rgb565(rgb):
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def rgb888(word):
    r, g, b = word >> 11, (word >> 5) & 63, word & 31
    return ((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2))


def render(doc, on):
    c = doc['canvas']
    assert (c['width'], c['height'], c['class'], c['touch']) == (240, 280, 'color', True)
    assert len(doc['pages']) == 1 and not doc['variables'], 'Only this example is supported'
    image = Image.new('RGB', (240, 280), c['background'])
    draw = ImageDraw.Draw(image)
    for e in doc['pages'][0]['elements']:
        assert e['kind'] in ('text', 'button') and e['font'] == 'sans'
        assert not e['binding'] and e['runtimeVisible'] and not e['editorHidden']
        assert e['action']['type'] in ('none', 'gpio')
        x, y, w, h = (e[k] for k in ('x', 'y', 'width', 'height'))
        if e['kind'] == 'button':
            assert (x, y, w, h, e['radius']) == (28, 168, 184, 68, 0), 'Update hardware hit area before exporting a different button'
            assert e['action'] == {'type': 'gpio', 'pin': 14, 'mode': 'toggle', 'level': False}
            draw.rectangle((x, y, x+w-1, y+h-1), fill='#35d58a' if on else e['fill'])
        font = ImageFont.truetype(str(FONT), e['fontSize'])
        # Match SVG dominant-baseline=central; text elements start at x, buttons center.
        anchor = 'mm' if e['kind'] == 'button' else 'lm'
        draw.text((x+w/2 if e['kind'] == 'button' else x, y+h/2), e['text'],
                  font=font, anchor=anchor, fill=e['color'])
    words = [rgb565(pixel) for pixel in image.getdata()]
    # Preview is expanded from the actual 16-bit values sent to ST7789.
    image.putdata([rgb888(word) for word in words])
    runs = []
    for word in words:
        if runs and runs[-1][1] == word and runs[-1][0] < 65535:
            runs[-1][0] += 1
        else:
            runs.append([1, word])
    return image, runs


def main():
    doc = json.loads(LAYOUT.read_text())
    doc.pop('hardwarePreview', None)
    frames = {}
    header = ['// Generated by scripts/export-touch-led169.py. Do not edit.',
              '#pragma once', '#include <stdint.h>',
              'namespace DisplayFrames {', 'struct Run { uint16_t count, color; };']
    for name, on in [('off', False), ('on', True)]:
        image, runs = render(doc, on)
        png = io.BytesIO()
        image.save(png, format='PNG')
        frames[name] = 'data:image/png;base64,' + base64.b64encode(png.getvalue()).decode()
        header.append(f'constexpr Run {name}[] = {{')
        header.extend('  {' + str(n) + ',0x' + format(color, '04x') + '},' for n, color in runs)
        header.append('};')
        print(f'{name}: {len(runs)} RGB565 runs, {len(png.getvalue())} PNG bytes')
    header.append('}')
    snapshot = {'target': 'TouchLed169/RGB565', 'source': doc, 'page': doc['pages'][0]['id'], 'pin': 14, 'frames': frames}
    (PROJECT / 'display_frames.h').write_text('\n'.join(header) + '\n')
    LAYOUT.write_text(json.dumps({**doc, 'hardwarePreview': snapshot}, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
